#ifndef IMAGEKIT_CAPABILITY_FLAGS_H
#define IMAGEKIT_CAPABILITY_FLAGS_H

/* Numeric contract for the capability-flags field of the codec catalog. */
/** Stable numeric codec capability bits shared by worker catalogs and clients. */
enum {
    IMAGE_CAPABILITY_STILL = 1,
    IMAGE_CAPABILITY_ANIMATION = 2,
    IMAGE_CAPABILITY_MULTI_IMAGE = 4,
    IMAGE_CAPABILITY_HIGH_DEPTH = 8,
    IMAGE_CAPABILITY_HDR = 16,
    IMAGE_CAPABILITY_REGION = 32,
    IMAGE_CAPABILITY_THUMBNAIL = 64,
    IMAGE_CAPABILITY_EMBEDDED_PREVIEW = 128,
    IMAGE_CAPABILITY_METADATA = 256,
    IMAGE_CAPABILITY_ENCODE = 512,
    IMAGE_CAPABILITY_VECTOR = 1024,
    IMAGE_CAPABILITY_GAIN_MAP = 2048,
    IMAGE_CAPABILITY_COLOR_MANAGED = 4096,
};

#endif
